#ifndef MIXRTS_GRIDMASK_HPP
#define MIXRTS_GRIDMASK_HPP


enum GridMask {
	GRIDMASK_RESOURCE          = 0xFF000000,
	GRIDMASK_HAS_CONCRETE      = 0x00100000,
	GRIDMASK_IS_FREE           = 0x00080000,
	GRIDMASK_BUILDABLE         = 0x00040000,
	GRIDMASK_CRATER_TYPE       = 0x00030000,
	GRIDMASK_TERRAIN_TYPE      = 0x0000F000,
	// GRIDMASK_               = 0x00000800,
	// GRIDMASK_               = 0x00000400,

	// Lowest byte is sent as is to the pathfinder
	GRIDMASK_SHIP_CAN_PASS     = 0x00000008,
	GRIDMASK_WORM_CAN_PASS     = 0x00000004,
	GRIDMASK_VEHICLES_CAN_PASS = 0x00000002,
	GRIDMASK_INFANTRY_CAN_PASS = 0x00000001,
};

#define GRIDMASK_ALL_CAN_PASS (GRIDMASK_INFANTRY_CAN_PASS | GRIDMASK_VEHICLES_CAN_PASS | GRIDMASK_SHIP_CAN_PASS)
#define GRIDMASK_CAN_BUILD (GRIDMASK_IS_FREE | GRIDMASK_BUILDABLE)
#define GRID_RESOURCE_TYPE(i) ((i & GRIDMASK_RESOURCE) >> 24 & 0x1F)
#define GRID_RESOURCE_COUNT(i) ((i & GRIDMASK_RESOURCE) >> 29)
#define GRID_CRATER_TYPE(i) ((i & GRIDMASK_CRATER_TYPE) >> 16)
#define GRID_TERRAIN_TYPE(i) ((i & GRIDMASK_TERRAIN_TYPE) >> 12)


#endif //MIXRTS_GRIDMASK_HPP
